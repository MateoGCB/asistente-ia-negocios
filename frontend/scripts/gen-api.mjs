// Generates src/api/schema.d.ts from the backend's OpenAPI document.
// Source: OPENAPI_SOURCE (a URL or a local file path), default http://localhost:8000/openapi.json
// (start the backend first; any database works, the document does not depend on data).
import { writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const source = process.env.OPENAPI_SOURCE ?? "http://localhost:8000/openapi.json";
const input = /^https?:\/\//.test(source) ? new URL(source) : pathToFileURL(source);
const ast = await openapiTS(input);
const header = "// Generated by `npm run gen:api` from the backend OpenAPI document. Do not edit by hand.\n";
await writeFile(new URL("../src/api/schema.d.ts", import.meta.url), header + astToString(ast));
console.log(`src/api/schema.d.ts generated from ${source}`);
